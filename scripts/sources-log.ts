// Regenerates data/sources.md: which wiki pages each era's events cite, with the
// revision that was read (from data/raw/manifest.json), plus coverage stats of the
// timeline candidates. Run after editing events:
//
//   npm run sources

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { events, eras } from "../data";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const manifest: Record<string, { revid: number; timestamp: string; url: string; redirectFrom?: string }> = JSON.parse(readFileSync(path.join(ROOT, "data/raw/manifest.json"), "utf8"));
const byUrl = new Map<string, { title: string; revid: number; timestamp: string }>();
for (const [title, m] of Object.entries(manifest)) byUrl.set(decodeURIComponent(m.url).replace(/ /g, "_"), { title, ...m });
const redirectTo = new Map<string, string>();
for (const [title, m] of Object.entries(manifest)) if (m.redirectFrom) redirectTo.set(m.redirectFrom.replace(/ /g, "_"), title);

function pageOf(url: string) {
  const u = decodeURIComponent(url.split("#")[0]);
  const hit = byUrl.get(u);
  if (hit) return hit;
  const slug = u.replace("https://cyberpunk.fandom.com/wiki/", "");
  const t = redirectTo.get(slug);
  if (t) return { title: t, revid: manifest[t].revid, timestamp: manifest[t].timestamp };
  return null;
}

const static_header = existsSync(path.join(ROOT, "data/sources.header.md")) ? readFileSync(path.join(ROOT, "data/sources.header.md"), "utf8") : "";

let out = static_header.trim() + "\n\n## Pages cited, by era\n\nGenerated by `npm run sources`. Revision ids are the versions read when the data was written.\n";
const missing: string[] = [];
for (const era of eras) {
  const evs = events.filter((e) => e.era === era.id);
  if (!evs.length) continue;
  const pages = new Map<string, { n: number; rev?: string }>();
  for (const e of evs) {
    const p = pageOf(e.wikiUrl);
    const key = p ? p.title : decodeURIComponent(e.wikiUrl.split("/wiki/")[1].split("#")[0]).replace(/_/g, " ");
    if (!p) missing.push(`${e.id} -> ${e.wikiUrl}`);
    const cur = pages.get(key) ?? { n: 0, rev: p ? `rev ${p.revid}, ${p.timestamp.slice(0, 10)}` : "not in local dump" };
    cur.n++;
    pages.set(key, cur);
  }
  out += `\n### ${era.name} (${evs.length} events)\n\n`;
  for (const [t, v] of [...pages.entries()].sort((a, b) => b[1].n - a[1].n || a[0].localeCompare(b[0]))) out += `- [${t}](https://cyberpunk.fandom.com/wiki/${encodeURIComponent(t.replace(/ /g, "_"))}): ${v.n} event${v.n > 1 ? "s" : ""} (${v.rev})\n`;
}

// Coverage of timeline candidates
const candPath = path.join(ROOT, "data/raw/timeline-candidates.json");
if (existsSync(candPath)) {
  const cands: { page: string }[] = JSON.parse(readFileSync(candPath, "utf8"));
  const by: Record<string, number> = {};
  for (const c of cands) by[c.page] = (by[c.page] ?? 0) + 1;
  out += `\n## Timeline entries reviewed\n\n`;
  for (const [p, n] of Object.entries(by)) out += `- ${p}: ${n} dated entries extracted\n`;
  out += `- Events in the app: ${events.length} (entries were merged, and some come from article pages rather than the timelines)\n`;
}
if (missing.length) out += `\n## Cited pages not in the local dump\n\n${missing.map((m) => `- ${m}`).join("\n")}\n`;

writeFileSync(path.join(ROOT, "data/sources.md"), out);
console.log(`sources.md written (${missing.length} cited pages not in dump)`);
